import * as assert from "assert";

import { DeviceNotificationMessage } from "../../messages/device-notification";

suite("Device Notification Test Suite", () => {
    test("Parses a color sensor record with reflected light", () => {
        const data = Uint8Array.from([
            0x3c, 0x53, 0x00, 0x02, 0x00, 0x64, 0x00, 0x64, 0x00, 0x64,
            0x64, 0x64, 0x64, 0x64, 0x64, 0x64, 0x64, 0x64, 0x64, 0x00,
            0x64, 0x64, 0x64, 0x00, 0x00, 0x00, 0x64, 0x00, 0x00, 0x01,
            0x00, 0x00, 0xc8, 0xff, 0xf9, 0xff, 0x01, 0x00, 0x0c, 0x00,
            0x02, 0x00, 0xe0, 0x03, 0x03, 0x00, 0xff, 0xff, 0x14, 0x00,
            0x00, 0x5a, 0x0a, 0x00, 0x30, 0x60, 0x00, 0x00, 0x00, 0x00,
            0x60, 0x00, 0x00, 0x00, 0x0a, 0x01, 0x30, 0x0e, 0x00, 0x00,
            0x00, 0x00, 0x0e, 0x00, 0x00, 0x00, 0x0c, 0x02, 0xff, 0x60,
            0x10, 0x02, 0x84, 0x01, 0x56, 0x01,
        ]);
        const message = new DeviceNotificationMessage();

        message.deserialize(data);

        assert.strictEqual(message.devices.length, 6);
        assert.deepStrictEqual(message.devices[5], {
            type: "color",
            port: 2,
            color: -1,
            colorName: "unknown",
            reflected: 96,
            red: 528,
            green: 388,
            blue: 342,
        });
    });

    test("Maps a detected color code to its SPIKE color name", () => {
        const message = new DeviceNotificationMessage();

        message.deserialize(Uint8Array.from([
            0x3c, 0x0a, 0x00,
            0x0c, 0x02, 0x09, 0x32, 0xff, 0x03, 0x00, 0x00, 0x00, 0x00,
        ]));

        assert.strictEqual(message.devices[0].color, 9);
        assert.strictEqual(message.devices[0].colorName, "red");
    });
});